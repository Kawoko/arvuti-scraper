-- ===========================================================================
-- Arvutitark Price Tracker - user tracking and notification preferences
-- ===========================================================================
-- Replaces the old hard-coded "custom" group with per-user favourites.
--
--   tracked_products       one row per (user, product, category) the user starred
--   notification_settings  how that user wants to be told about price drops
--
-- Both tables are protected by Row Level Security: a signed-in user can only
-- ever read or change rows whose `user_id` equals `auth.uid()`. The scraper and
-- other server-side code use the service role and bypass RLS.
--
-- Email delivery and webhook sending are intentionally NOT implemented here.
-- This migration only stores the preference so the delivery worker can be added
-- later without another data migration.
--
-- Safe to re-run.
-- ===========================================================================

create table if not exists public.tracked_products (
  id                bigint generated by default as identity primary key,
  user_id           uuid        not null references auth.users (id) on delete cascade,
  product_id        bigint      not null,
  category          text        not null,
  -- The latest price at the moment the product was starred. This is what makes
  -- "dropped 10% since I started tracking it" possible later.
  price_at_tracking numeric(12, 2),
  created_at        timestamptz not null default now(),
  unique (user_id, product_id, category)
);

comment on table public.tracked_products is
  'Products a signed-in user has starred. One row per user/product/category.';

create index if not exists tracked_products_user_idx
  on public.tracked_products (user_id, created_at desc);

-- Add the snapshot column when upgrading an earlier installation.
alter table public.tracked_products
  add column if not exists price_at_tracking numeric(12, 2);

create table if not exists public.notification_settings (
  user_id             uuid        primary key references auth.users (id) on delete cascade,
  -- Minimum drop, in percent, before an alert is worth sending.
  price_drop_percent  integer     not null default 10
    check (price_drop_percent between 1 and 90),
  email_enabled       boolean     not null default false,
  email_address       text,
  discord_webhook_url text,
  webhook_enabled     boolean     not null default false,
  webhook_url         text,
  updated_at          timestamptz not null default now()
);

comment on table public.notification_settings is
  'Per-user alert threshold and delivery preferences. Delivery itself is not wired up yet.';

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists notification_settings_touch on public.notification_settings;
create trigger notification_settings_touch
  before update on public.notification_settings
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------

alter table public.tracked_products        enable row level security;
alter table public.notification_settings   enable row level security;

drop policy if exists "Users read their tracked products"   on public.tracked_products;
drop policy if exists "Users add their tracked products"    on public.tracked_products;
drop policy if exists "Users update their tracked products" on public.tracked_products;
drop policy if exists "Users remove their tracked products" on public.tracked_products;

create policy "Users read their tracked products"
  on public.tracked_products for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Users add their tracked products"
  on public.tracked_products for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "Users update their tracked products"
  on public.tracked_products for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "Users remove their tracked products"
  on public.tracked_products for delete
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Users read their notification settings"   on public.notification_settings;
drop policy if exists "Users insert their notification settings" on public.notification_settings;
drop policy if exists "Users update their notification settings" on public.notification_settings;

create policy "Users read their notification settings"
  on public.notification_settings for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Users insert their notification settings"
  on public.notification_settings for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "Users update their notification settings"
  on public.notification_settings for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

grant select, insert, update, delete on public.tracked_products      to authenticated;
grant select, insert, update, delete on public.notification_settings to authenticated;
grant usage, select on sequence public.tracked_products_id_seq to authenticated;

-- ---------------------------------------------------------------------------
-- Convenience view: tracked rows joined to their live price statistics.
--
-- `security_invoker` makes the underlying tracked_products RLS apply, so the
-- view can never leak another user's favourites even though it is queryable.
-- ---------------------------------------------------------------------------

create or replace view public.tracked_product_details
with (security_invoker = true)
as
select
  tp.user_id,
  tp.created_at              as tracked_at,
  tp.price_at_tracking,
  pps.*
from public.tracked_products tp
join public.product_price_summary pps
  on pps.product_id = tp.product_id
 and pps.category   = tp.category;

comment on view public.tracked_product_details is
  'Starred products joined to their current price summary. Scoped to the caller by RLS.';

grant select on public.tracked_product_details to authenticated;
